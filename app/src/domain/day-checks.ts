import type { DeskItem } from './workdesk';
import { iso, shift } from './management';
export interface DayCheck {
  id: string;
  title: string;
  why: string;
  instruction: string;
  items: DeskItem[];
}
export function dayChecks(items: DeskItem[], now: Date, closing = false): DayCheck[] {
  const today = iso(now),
    inWeek = shift(today, 7);
  const topics = [
    'Проверить ближайшие события',
    'Проверить команды и загрузку',
    'Проверить планы и зависимости',
    'Подготовить разговоры о людях',
    'Проверить вопросы для согласования',
    'Разобрать исключения недели',
    'Проверить ближайшие события',
  ];
  return [
    {
      id: 'agreements',
      title: closing ? 'Проверить, что осталось незавершённым' : 'Проверить договорённости',
      why: 'Чтобы не потерять обещания и ответы, которые вы ждёте.',
      instruction:
        'Посмотрите записи ниже. Затем вручную проверьте почту и переписку: они не подключены к порталу. Найденное обязательство запишите; если вопросов нет, завершите проверку без задачи.',
      items: items.filter((i) => i.ref && i.attention && i.source !== 'Встреча'),
    },
    {
      id: 'topic',
      title: topics[now.getDay()]!,
      why: 'Это проверка по теме дня, а не требование заполнить все разделы.',
      instruction:
        now.getDay() === 5
          ? 'Есть ли повторяющиеся сбои, нерешённые вопросы или наступившие даты проверки эффекта? Сначала проверьте основания. Системную проблему оформляйте только если она требует вашего уровня и изменения процесса.'
          : 'Проверьте вопросы по теме дня на основе доступных данных. Если фактов не хватает, уточните их у участников; отсутствие записей не подтверждает отсутствие проблем.',
      items: items.filter((i) => !i.ref || (i.ref.area === 'crm' && i.ref.kind === 'meeting')),
    },
    {
      id: 'upcoming',
      title: 'Посмотреть ближайшую неделю',
      why: 'Чтобы подготовиться к встречам и срокам заранее.',
      instruction:
        'Проверьте события ниже и внешний календарь вручную. Время встреч из внешнего календаря портал пока не получает. Для подготовки при необходимости создайте действие.',
      items: items
        .filter((i) => i.date && i.date >= today && i.date <= inWeek)
        .sort((a, b) => a.date.localeCompare(b.date)),
    },
  ];
}
